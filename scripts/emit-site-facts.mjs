#!/usr/bin/env node
/**
 * emit-site-facts.mjs — generate dist/facts.js + dist/facts.json from compiled
 * brainclaw modules. The site (brainclaw-site repo) imports these as the
 * single source of truth for tool counts, entity names, version, etc.
 *
 * Build-chain dependency: must run AFTER tsc has produced dist/. Hooked into
 * `build:cli` after copy-default-profiles.
 *
 * Sprint 0 of pln_7fdfd70d (site content-as-data + facts-contract).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const pkg = JSON.parse(readFileSync('./package.json', 'utf-8'))

const distMcpUrl = pathToFileURL(path.resolve('./dist/commands/mcp.js'))
const distRegUrl = pathToFileURL(path.resolve('./dist/core/entity-registry.js'))

const { MCP_TOOL_NAMES, PUBLISHED_TOOLS } = await import(distMcpUrl.href)
const { ENTITY_NAMES, ENTITY_REGISTRY } = await import(distRegUrl.href)

const facts = {
  version: pkg.version,
  generated_at: new Date().toISOString(),
  tools: {
    count: MCP_TOOL_NAMES.length,
    published_count: PUBLISHED_TOOLS.length,
    names: MCP_TOOL_NAMES,
  },
  entities: {
    count: ENTITY_NAMES.length,
    names: ENTITY_NAMES,
    short_label_prefixes: Object.fromEntries(
      ENTITY_NAMES.map((n) => [n, ENTITY_REGISTRY[n].shortLabelPrefix]),
    ),
  },
}

const jsContent =
  `// Generated by scripts/emit-site-facts.mjs at build time. Do not edit manually.\n` +
  `// Source: brainclaw v${facts.version} on ${facts.generated_at}\n` +
  `export const FACTS = ${JSON.stringify(facts, null, 2)}\n` +
  `export default FACTS\n`

writeFileSync('./dist/facts.js', jsContent, 'utf-8')
writeFileSync('./dist/facts.json', JSON.stringify(facts, null, 2) + '\n', 'utf-8')

console.log(
  `✓ Generated dist/facts.js + dist/facts.json (v${facts.version}, ${facts.tools.count} tools, ${facts.entities.count} entities)`,
)
