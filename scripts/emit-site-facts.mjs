#!/usr/bin/env node
/**
 * emit-site-facts.mjs — generate dist/facts.js + dist/facts.json from compiled
 * brainclaw modules. The site (brainclaw-site repo) imports these as the
 * single source of truth for tool counts, entity names, version, etc.
 *
 * Build-chain dependency: must run AFTER tsc has produced dist/. Hooked into
 * `build:cli` after copy-default-profiles.
 *
 * Sprint 0 of pln_7fdfd70d (site content-as-data + facts-contract).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const pkg = JSON.parse(readFileSync('./package.json', 'utf-8'))

const distMcpUrl = pathToFileURL(path.resolve('./dist/commands/mcp.js'))
const distRegUrl = pathToFileURL(path.resolve('./dist/core/entity-registry.js'))
const distAgentCapabilityUrl = pathToFileURL(path.resolve('./dist/core/agent-capability.js'))

const { MCP_TOOL_NAMES, PUBLISHED_TOOLS } = await import(distMcpUrl.href)
const { ENTITY_NAMES, ENTITY_REGISTRY } = await import(distRegUrl.href)
const { getAllAgentCapabilityProfiles } = await import(distAgentCapabilityUrl.href)

const agentProfiles = getAllAgentCapabilityProfiles()
  .map((profile) => ({
    name: profile.name,
    category: profile.category,
    workflow_model: profile.workflowModel,
    tier: profile.templateTier,
    has_mcp: profile.hasMcp,
    has_hooks: profile.hasHooks,
    has_skills: profile.hasSkills,
    has_rules: profile.hasRules,
    instruction_file: profile.instructionFile,
    mcp_config_scope: profile.mcpConfigScope,
    role_capabilities: profile.role_capabilities,
    max_concurrent_tasks: profile.max_concurrent_tasks,
  }))
  .sort((a, b) => a.name.localeCompare(b.name))

// Bench report is optional: when scripts/bench.mjs has run, we publish a
// summary alongside tools/entities so the site can render a measured
// "time-to-first-value" section. Absent when the bench hasn't run yet.
const benchReportPath = path.resolve('./dist/bench-report.json')
let benchSummary
if (existsSync(benchReportPath)) {
  try {
    const raw = JSON.parse(readFileSync(benchReportPath, 'utf-8'))
    benchSummary = {
      schema: raw.schema,
      generated_at: raw.generated_at,
      node_version: raw.node_version,
      platform: raw.platform,
      repeats: raw.repeats,
      scenarios: raw.scenarios.map((s) => ({
        name: s.name,
        volume: s.volume,
        description: s.description,
        duration_ms_median: s.duration_ms.median,
        payload_chars_median: s.payload_chars.median,
        payload_tokens_est_median: s.payload_tokens_est.median,
      })),
    }
  } catch (err) {
    console.warn(`[emit-site-facts] failed to parse bench report: ${err instanceof Error ? err.message : err}`)
  }
}

const facts = {
  version: pkg.version,
  generated_at: new Date().toISOString(),
  tools: {
    count: MCP_TOOL_NAMES.length,
    published_count: PUBLISHED_TOOLS.length,
    names: MCP_TOOL_NAMES,
  },
  entities: {
    count: ENTITY_NAMES.length,
    names: ENTITY_NAMES,
    short_label_prefixes: Object.fromEntries(
      ENTITY_NAMES.map((n) => [n, ENTITY_REGISTRY[n].shortLabelPrefix]),
    ),
  },
  agent_integrations: {
    count: agentProfiles.length,
    names: agentProfiles.map((profile) => profile.name),
    profiles: agentProfiles,
  },
  ...(benchSummary ? { bench: benchSummary } : {}),
}

const jsContent =
  `// Generated by scripts/emit-site-facts.mjs at build time. Do not edit manually.\n` +
  `// Source: brainclaw v${facts.version} on ${facts.generated_at}\n` +
  `export const FACTS = ${JSON.stringify(facts, null, 2)}\n` +
  `export default FACTS\n`

writeFileSync('./dist/facts.js', jsContent, 'utf-8')
writeFileSync('./dist/facts.json', JSON.stringify(facts, null, 2) + '\n', 'utf-8')

console.log(
  `✓ Generated dist/facts.js + dist/facts.json (v${facts.version}, ${facts.tools.count} tools, ${facts.entities.count} entities, ${facts.agent_integrations.count} agent integrations${benchSummary ? `, bench: ${benchSummary.scenarios.length} scenario(s)` : ''})`,
)
